"""教师发展竞赛模块：比赛方案、教学设计、讲稿、答辩预测。"""


def competition_plan(course, major, topic):
    return f"""# {course}教学能力比赛方案

一、比赛定位
围绕高职{course}课程建设，以{topic}为参赛内容，体现任务驱动、理实一体、岗位能力培养与课程思政。

二、教学设计要点
1. 依据课程标准与人才培养方案确定教学目标；
2. 采用项目化教学，按“任务导入→传授新知→任务实施→总结提升”组织；
3. 融入岗位情境与真实案例，突出职业教育特色；
4. 设置多元评价（随堂、实操、学习通测评）。

三、实施步骤
1. 编写教学设计；2. 制作课件与任务单；3. 录制课堂实录；4. 撰写教学实施报告；5. 答辩模拟。

四、成果材料
教学设计、PPT、讲稿、课堂实录、教学反思、答辩问题集。
"""


def lesson_design(course, major, topic):
    return f"""# {course}教学设计（{topic}）

## 一、基本信息
课程：{course}    专业：{major}    课题：{topic}    课时：2课时（90min）

## 二、教学目标
知识目标、能力目标、素质目标（与课程标准一致）。

## 三、重难点
重点：核心知识点；难点：抽象逻辑与岗位应用。

## 四、教学过程
考勤2min → 复习3min → 预热7min → 引入5min → 新知48min → 实施20min → 总结3min → 作业2min。

## 五、评价设计
过程评价40% + 终结评价60%；随堂练习、任务单、学习通测评。

## 六、思政融入
结合安全生产、工程责任、职业规范、交通强国、岗位使命五维方向自然融入。
"""


def speech_script(course, major, topic):
    return f"""# {course}说课讲稿（{topic}）

尊敬的各位评委：
我今天说课的题目是《{topic}》，选自《{course}》。我将从课程定位、教学目标、学情分析、教学过程、评价设计五个方面进行说明。

一、课程定位：{course}面向{major}专业，服务岗位能力培养。
二、教学目标：围绕知识、能力、素质三维目标设计。
三、学情分析：学生已具备基础认知，需借助情境与任务提升应用能力。
四、教学过程：采用“课前-课中-课后”闭环，课中按90分钟时间链组织。
五、评价设计：多元评价与过程考核结合。

谢谢各位评委。
"""


def defense_questions(course, major, topic):
    return f"""# {course}答辩问题预测（{topic}）

1. 本节课教学目标如何对应课程标准与岗位能力？
2. 为什么选择项目化/任务驱动教学？预期效果是什么？
3. 如何评价学生课堂任务完成情况？
4. 思政元素如何自然融入专业教学？
5. 若学生基础差异大，您如何分层教学？
"""
